export function getUniversityById(id: number): University | undefined {
  return UNIVERSITIES.find((u) => u.id === id);
}

export function getUniversitiesByRegion(region: string): University[] {
  if (!region || region.trim().toLowerCase() === 'tất cả') {
    return UNIVERSITIES;
  }
  return UNIVERSITIES.filter((u) => u.region.toLowerCase() === region.trim().toLowerCase());
}

export function getHollandName(code: string): string {
  if (!code) return 'Không xác định';
  const c = code.toUpperCase().trim() as HollandCode;
  return HOLLAND_NAMES[c] || 'Chưa xác định';
}

export function getHollandDescription(code: string): string {
  if (!code) return '';
  const c = code.toUpperCase().trim() as HollandCode;
  return HOLLAND_DESCRIPTIONS[c] || '';
}

export function getHollandMajors(code: string): string[] {
  if (!code) return [];
  const c = code.toUpperCase().trim() as HollandCode;
  return HOLLAND_MAJORS[c] || [];
}

export function getAverageCutoffScore(uni: University): number {
  const scores = Object.values(uni.cutoffScores);
  if (!scores.length) return uni.score2024 || 24.0;
  const sum = scores.reduce((acc, curr) => acc + curr, 0);
  return Number((sum / scores.length).toFixed(2));
}

