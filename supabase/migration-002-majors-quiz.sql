-- 1. BẢNG MAJORS
create table if not exists public.majors (
  id bigint generated by default as identity primary key,
  university_id bigint not null references public.universities(id) on delete cascade,
  name text not null,
  cutoff numeric(4,1) not null check (cutoff between 0 and 30),
  unique(university_id, name)
);

-- Bật RLS cho majors
alter table public.majors enable row level security;

-- Policy SELECT công khai tương tự bảng universities
create policy "majors_select_all" on public.majors
  for select using (true);

-- 2. BẢNG QUIZ_RESULTS (KẾT QUẢ TRẮC NGHIỆM HOLLAND)
create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  profile_email text not null,
  scores jsonb not null,
  primary_code text not null,
  secondary_code text,
  created_at timestamptz default now()
);

-- Bật RLS cho quiz_results
alter table public.quiz_results enable row level security;

-- Policies SELECT / INSERT / UPDATE theo email chủ kết quả (bám sát mẫu applications)
create policy "quiz_results_select_scoped" on public.quiz_results
  for select using (
    public.current_user_role() = 'admin'
    or lower(profile_email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );

create policy "quiz_results_insert_own" on public.quiz_results
  for insert with check (
    lower(profile_email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );

create policy "quiz_results_update_scoped" on public.quiz_results
  for update using (
    public.current_user_role() = 'admin'
    or lower(profile_email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
